import '@testing-library/jest-dom';

// Fetch API globals come from jest.environment.cjs.

// jsdom doesn't implement matchMedia; ThemeProvider uses it for the system theme.
if (!window.matchMedia) {
  Object.defineProperty(window, 'matchMedia', {
    writable: true,
    value: (query: string) => ({
      matches: false,
      media: query,
      onchange: null,
      addEventListener: () => {},
      removeEventListener: () => {},
      addListener: () => {},
      removeListener: () => {},
      dispatchEvent: () => false,
    }),
  });
}
